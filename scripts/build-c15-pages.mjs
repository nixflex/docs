// Final coordinated authoring layer. Run after the historical builders.
import fs from 'node:fs';
import path from 'node:path';
const root=path.resolve(import.meta.dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8').replaceAll('\r\n','\n');
const write=(p,s)=>{const f=path.join(root,p);fs.mkdirSync(path.dirname(f),{recursive:true});if(!fs.existsSync(f)||read(p)!==s)fs.writeFileSync(f,s);};
const plan=JSON.parse(read('spec-source/c15-pages.json'));
const config=JSON.parse(read('docs.json'));
for(const [slug,source] of Object.entries(plan.sources))write(slug+'.mdx',read(source));
for(const [slug,metadata] of Object.entries(plan.metadata)){
 let s=read(slug+'.mdx');
 // Historical Knowledge builders predate the current package inventory.
 s=s.replaceAll('MCP has 94 registered tools, including 19 Knowledge tools.',`MCP has ${plan.kits.mcp.tools} registered tools, including 19 Knowledge tools.`);
 for(const [key,value] of Object.entries({...metadata,canonical:'https://docs.nixflex.com/'+(slug==='index'?'':slug)})){
  const line=key+': '+JSON.stringify(value),pattern=new RegExp('^'+key+':.*$','m');
  if(!pattern.test(s))throw Error('Missing frontmatter '+key+' in '+slug);
  s=s.replace(pattern,line);
 }
 for(const [old,target]of Object.entries(plan.retired))s=s.replaceAll('(/'+old+')','(/'+target+')').replaceAll('(/'+old+'#','(/'+target+'#').replaceAll('href="/'+old+'"','href="/'+target+'"').replaceAll('href="/'+old+'#','href="/'+target+'#');
 if(s.includes('DOCS-PENDING'))throw Error('Unresolved deletion authoring note: '+slug);
 write(slug+'.mdx',s);
}
// Retired sources are regenerated by older builders, then removed from publication.
for(const slug of Object.keys(plan.retired)){
 const file=path.join(root,slug+'.mdx');if(fs.existsSync(file))fs.unlinkSync(file);
}
// A useful operation directory also gives every endpoint a body link from an index.
const flatten=v=>typeof v==='string'?[v]:Array.isArray(v)?v.flatMap(flatten):['groups','pages'].flatMap(k=>v?.[k]?flatten(v[k]):[]);
let directory='\n\n## Find an API operation\n\nChoose a resource below for the exact request fields, responses and recovery steps. These are the 151 public HTTP operations; webhook events and dashboard-only personal actions are separate.\n\n<AccordionGroup>\n';
for(const group of plan.navigation.tabs.find(t=>t.tab==='API reference').groups){
 const rows=flatten(group).map(slug=>({slug,binding:read(slug+'.mdx').match(/^openapi: "\/api-reference\/public.openapi.json ([^"]+)"$/m)?.[1]})).filter(r=>r.binding);
 if(!rows.length)continue;
 directory+='\n<Accordion title='+JSON.stringify(group.group+' ('+rows.length+')')+'>\n\n| Task | Method and path |\n| --- | --- |\n';
 for(const row of rows)directory+='| ['+plan.metadata[row.slug].title+'](/'+row.slug+') | `'+row.binding+'` |\n';
 directory+='\n</Accordion>\n';
}
directory+='\n</AccordionGroup>\n';
const intro=read('api-reference/introduction.mdx').split('\n\n## Find an API operation\n')[0].trimEnd();
write('api-reference/introduction.mdx',intro+directory);
config.navigation=plan.navigation;
config.redirects=plan.redirects;
config.seo={...config.seo,indexing:'all',metatags:{...config.seo?.metatags,canonical:'https://docs.nixflex.com'}};
for(const key of ['title','description','og:title','og:description','og:image','twitter:title','twitter:description','twitter:image','robots'])delete config.seo.metatags[key];
write('docs.json',JSON.stringify(config,null,2)+'\n');
console.log('C15: '+Object.keys(plan.metadata).length+' pages, '+Object.keys(plan.sources).length+' final authored sources, '+Object.keys(plan.retired).length+' consolidated topics.');
